void on_post_fs_data(void)
{
    static bool done = false;

    if (done) {
        pr_info("on_post_fs_data already done\n");
        return;
    }

    done = true;
    pr_info("on_post_fs_data!\n");

    ksu_load_allow_list();
#ifdef CONFIG_KSU_DYNAMIC_MANAGER
    ksu_dynamic_manager_load();
#endif
    ksu_observer_init();
    // Sanity check for safe mode only needs early-boot input samples.
    ksu_stop_input_hook_runtime();
    ksu_selinux_hide_handle_post_fs_data();
    ksu_feature_apply_forced();
}

extern void ext4_unregister_sysfs(struct super_block *sb);

int nuke_ext4_sysfs(const char *mnt)
{
    struct path path;
    int err = kern_path(mnt, 0, &path);

    if (err) {
        pr_err("nuke path err: %d\n", err);
        return err;
    }

    if (strcmp(path.dentry->d_inode->i_sb->s_type->name, "ext4") != 0) {
        pr_info("nuke but module aren't mounted\n");
        path_put(&path);
        return -EINVAL;
    }

    ext4_unregister_sysfs(path.dentry->d_inode->i_sb);
    path_put(&path);
    return 0;
}

void on_module_mounted(void)
{
    pr_info("on_module_mounted!\n");
    ksu_module_mounted = true;
}

void on_boot_completed(void)
{
    ksu_boot_completed = true;
    pr_info("on_boot_completed!\n");
    /*
     * The LKM can be initialized before Android has published a complete
     * /data/system/packages.list.  An early throne scan then deliberately
     * fails closed, and a prune-only pass here can never recover: both the
     * built-in FinaSU manager and any additional trusted manager remain
     * uncrowned until packages.list happens to change again.
     *
     * Boot completion is the first reliable point at which package metadata
     * and /data/app are both ready.  Run the normal certificate-verified scan
     * here as a recovery pass; it still prunes the allowlist afterwards.
     */
    track_throne(false);
    ksu_selinux_hide_drop_backup_if_unused();
}
